"""Load: core tables -> data/processed/*.parquet (§7.4), data/core/seed.sql and (optionally) Postgres.

Usage (from Backend/):
    .venv/Scripts/python -m pipeline.load            # build Parquet + seed.sql only
    .venv/Scripts/python -m pipeline.load --apply    # also apply sql/*.sql + seed to DATABASE_URL

DATABASE_URL is read from the environment or from ../.env
(postgresql://user:pass@host:port/db). The core schema is rebuilt on every
apply: it is fully derived from the raw PSI files (L0).
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys
from datetime import date, datetime

import pandas as pd

from . import config
from .transform import build_core
from .utils import write_parquet

SQL_DIR = config.BACKEND / "sql"
CORE_OUT = config.DATA_DIR / "core"

# Load order (respects foreign keys).
LOAD_ORDER = [
    "dim_family_group", "dim_family", "dim_platform", "dim_investigation",
    "dim_hardware", "bridge_investigation_hardware",
    "dim_fuel_class", "dim_material", "dim_variable_group", "dim_unit", "dim_variable",
    "dim_outcome", "dim_date", "dim_source_table", "dim_file_kind", "map_source_column", "data_decision",
    "fact_test_run", "fact_measurement", "test_step", "fact_log_entry", "fact_file",
]
BATCH = 500


def sql_literal(v) -> str:
    if v is None or v is pd.NA or v is pd.NaT:
        return "NULL"
    if isinstance(v, float) and math.isnan(v):
        return "NULL"
    if isinstance(v, bool) or type(v).__name__ == "bool_":
        return "true" if v else "false"
    if isinstance(v, (int, float)) or type(v).__module__ == "numpy":
        return repr(v.item() if hasattr(v, "item") else v)
    if isinstance(v, (date, datetime)):
        return f"'{v.isoformat()}'"
    if isinstance(v, (list, tuple)) or type(v).__name__ == "ndarray":
        return "ARRAY[" + ",".join(sql_literal(x) for x in v) + "]::text[]" if len(v) else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def to_sql(tables: dict[str, pd.DataFrame]) -> str:
    out = ["-- Generated by pipeline.load. Do not edit by hand.", "BEGIN;", "SET search_path = core, public;"]
    out += [f"DELETE FROM {t};" for t in reversed(LOAD_ORDER)]
    for name in LOAD_ORDER:
        df = tables[name].astype(object).where(tables[name].notna(), None)
        cols = ", ".join(df.columns)
        records = df.to_dict("records")
        for i in range(0, len(records), BATCH):
            chunk = records[i:i + BATCH]
            rows = ",\n  ".join("(" + ", ".join(sql_literal(r[c]) for c in df.columns) + ")" for r in chunk)
            out.append(f"INSERT INTO {name} ({cols}) VALUES\n  {rows};")
    out.append("COMMIT;")
    return "\n".join(out) + "\n"


def export_processed(t: dict[str, pd.DataFrame]) -> list[str]:
    """L2 Parquet exchanged between the two ETLs (§7.4), plus the data dictionary (R17)."""
    inv = t["dim_investigation"][["investigation_id", "accession"]].rename(columns={"accession": "psi_id"})
    st = t["dim_source_table"][["source_table_id", "file_name", "owner"]].rename(columns={"file_name": "source_file"})
    out = t["dim_outcome"][["outcome_id", "code"]].rename(columns={"code": "outcome"})
    mat = t["dim_material"][["material_id", "code"]].rename(columns={"code": "material"})
    var = t["dim_variable"][["variable_id", "code"]].rename(columns={"code": "variable"})

    tests = (t["fact_test_run"].merge(inv, on="investigation_id").merge(st, on="source_table_id")
             .merge(out, on="outcome_id").merge(mat, on="material_id", how="left"))
    ids = t["fact_test_run"][["test_run_id", "test_id"]]
    files = {
        "investigations": t["dim_investigation"],
        "tests": tests.drop(columns=["investigation_id", "source_table_id", "outcome_id", "material_id"]),
        "measurements": t["fact_measurement"].merge(ids, on="test_run_id").merge(var, on="variable_id")
                        .drop(columns=["test_run_id", "variable_id", "measurement_id"]),
        "test_steps": t["test_step"].merge(ids, on="test_run_id").drop(columns="test_run_id"),
        "log_entries": t["fact_log_entry"].merge(inv, on="investigation_id").merge(st, on="source_table_id")
                       .drop(columns=["investigation_id", "source_table_id"]),
        "decisions": t["data_decision"],
    }
    v = t["dim_variable"].merge(t["dim_unit"].rename(columns={"code": "unit"}), on="unit_id") \
        .merge(t["dim_variable_group"].rename(columns={"code": "variable_group"}), on="variable_group_id")
    m = t["map_source_column"].merge(t["dim_source_table"][["source_table_id", "table_key"]], on="source_table_id")
    m = m[m["variable_id"].notna()].assign(src=lambda d: d["table_key"] + "." + d["column_name"])
    srcs = m.groupby("variable_id")["src"].agg(lambda s: ", ".join(sorted(s)))
    v["source_columns"] = v["variable_id"].map(srcs)
    files["data_dictionary"] = v[["code", "label", "variable_group", "unit", "measured_or_calculated",
                                  "is_core", "description", "source_columns"]].rename(columns={"code": "variable"})
    written = []
    for name, df in files.items():
        write_parquet(df, name, config.PROCESSED_DIR)
        written.append(name)
    files["data_dictionary"].to_csv(config.PROCESSED_DIR / "data_dictionary.csv", index=False)
    return written


def _database_url() -> str | None:
    if os.environ.get("DATABASE_URL"):
        return os.environ["DATABASE_URL"]
    env = config.BACKEND.parent / ".env"
    if env.exists():
        for line in env.read_text(encoding="utf-8").splitlines():
            if line.strip().startswith("DATABASE_URL="):
                return line.split("=", 1)[1].strip().strip('"').strip("'")
    return None


def apply(seed_sql: str) -> None:
    import psycopg2  # only needed for --apply

    url = _database_url()
    if not url:
        raise SystemExit("DATABASE_URL is missing (environment variable or .env at the repo root).")
    with psycopg2.connect(url) as conn, conn.cursor() as cur:
        for f in sorted(SQL_DIR.glob("*.sql")):
            print(f"applying {f.name}")
            cur.execute(f.read_text(encoding="utf-8"))
        conn.commit()
        print("loading seed")
        conn.autocommit = True   # the seed manages its own transaction
        cur.execute(seed_sql)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="apply DDL + seed to DATABASE_URL")
    a = ap.parse_args()

    tables = build_core()
    issues = tables.pop("_issues")
    written = export_processed(tables)
    CORE_OUT.mkdir(parents=True, exist_ok=True)
    seed = to_sql(tables)
    (CORE_OUT / "seed.sql").write_text(seed, encoding="utf-8", newline="\n")

    runs = tables["fact_test_run"].merge(tables["dim_outcome"], on="outcome_id")
    report = {
        "rows": {k: int(len(v)) for k, v in tables.items()},
        "outcomes": runs["code"].value_counts().to_dict(),
        "invalid_tests": int((~runs["is_valid"]).sum()),
        "pending_flags": int(runs["quality_flags"].map(lambda f: any(x.startswith("pending:") for x in f)).sum()),
        "processed_parquet": written,
        "seed_mb": round(len(seed.encode()) / 1e6, 2),
        "issues": issues.to_dict("records"),
    }
    (CORE_OUT / "_load_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    print(json.dumps(report, indent=2, ensure_ascii=False, default=str))
    if a.apply:
        apply(seed)
        print("done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
