-- =====================================================================
-- Flame in Freefall · servicio RAG (independiente del backend web)
-- Vive en la base del servicio RAG, no en la del tablero. Requiere pgvector.
--
-- No tiene claves foráneas hacia el backend: el vínculo con el tablero es
-- por `accession` (ej. 'PSI-69') y `doi`, que son estables en PSI. El backend
-- recibe esas claves en cada cita y las completa con dim_investigation.
-- =====================================================================
CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA IF NOT EXISTS rag;

CREATE TABLE IF NOT EXISTS rag.document (
    document_id  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accession    text NOT NULL,                 -- 'PSI-69' (clave compartida con el backend)
    doi          text,                          -- DOI de la investigación, para citar
    s3_key       text,                          -- archivo de PSI del que sale el documento
    sha256       text NOT NULL,
    file_name    text NOT NULL,
    title        text,
    category     text,                          -- Reports / Science Documents / Presentations ...
    n_pages      int,
    source_url   text,
    UNIQUE (accession, sha256)                  -- el mismo PDF puede estar en varias investigaciones
);
CREATE INDEX IF NOT EXISTS ix_document_accession ON rag.document (accession);

-- La dimensión del vector depende del modelo de embeddings: ajustar antes de cargar.
CREATE TABLE IF NOT EXISTS rag.chunk (
    chunk_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id int NOT NULL REFERENCES rag.document ON DELETE CASCADE,
    chunk_index int NOT NULL,
    page_from   int,
    page_to     int,
    content     text NOT NULL,
    tokens      int,
    chunk_kind  text NOT NULL DEFAULT 'text' CHECK (chunk_kind IN ('text', 'table')),  -- 'table' = mostly numbers
    embedding   vector(384),                    -- BAAI/bge-small-en-v1.5
    tsv         tsvector GENERATED ALWAYS AS (to_tsvector('english', content)) STORED,
    UNIQUE (document_id, chunk_index)
);
CREATE INDEX IF NOT EXISTS ix_chunk_tsv ON rag.chunk USING gin (tsv);
CREATE INDEX IF NOT EXISTS ix_chunk_embedding ON rag.chunk USING hnsw (embedding vector_cosine_ops);
